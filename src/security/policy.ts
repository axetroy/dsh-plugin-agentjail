/**
 * Policy templates.
 *
 * A template is a named, self-contained set of AgentJail rules expressed as a
 * Rego module plus the configuration fragment it expects. Templates let a
 * deployment start from a reviewed baseline — "read only", "no egress", "no
 * credential access" — instead of an empty policy file.
 *
 * The plugin does not evaluate Rego itself; AgentJail's OPA engine does. A
 * template's job is to be written to the daemon's policy directory and loaded by
 * the daemon, so the verdicts stay in one engine and one audit trail.
 *
 * Every template lands in its own Rego package, and a generated entrypoint
 * merges them into the single `agentjail.dsh.decision` document the daemon
 * reads. Separate packages are what make templates composable: two modules that
 * both declared `deny_rules` in one package would fail to load as a
 * redeclaration, so `renderTemplateBundle` always emits the entrypoint that
 * unions them. The generated sources are checked against a real OPA binary in
 * the test suite.
 * @module dsh-plugin-agentjail/security/policy
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/** One rule a template contributes. */
export interface PolicyRule {
  /** Rule identifier, unique within its template. */
  id: string
  /** Whether a match denies the call or asks a human about it. */
  kind: 'deny' | 'ask'
  /** Human-readable justification, recorded with the verdict. */
  reason: string
  /** Rego rule body — the statements that must hold for this rule to match. */
  body: string
}

/** A named policy template. */
export interface PolicyTemplate {
  /** Stable template name used to select it in configuration. */
  name: string
  /** One-line description of the posture this template enforces. */
  description: string
  /** Rules this template contributes. */
  rules: readonly PolicyRule[]
  /** Helper rules and constants the rule bodies reference. */
  helpers?: string
  /**
   * Whether the template is a complete posture (replaces the baseline) or an
   * additive restriction layered over the daemon's built-in rules.
   */
  kind: 'baseline' | 'additive'
  /** Rendered Rego module source. Populated by {@link renderTemplateModule}. */
  readonly rego?: string
}

/** Package every rendered module lives under, so the entrypoint can import them. */
export const POLICY_PACKAGE = 'agentjail.dsh'

/** Package prefix a single template's module is placed in. */
export const TEMPLATE_PACKAGE_PREFIX = `${POLICY_PACKAGE}.templates`

/** File name of the generated entrypoint, sorting after every template file. */
export const ENTRYPOINT_FILE = '99-decision.rego'

/**
 * Convert a template name into a Rego package path segment.
 * @param name - the template name.
 * @returns the package path segment.
 */
export function templatePackage(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, '_')
}

/** Render one rule as a `contains` statement with its guard body. */
function renderRule(rule: PolicyRule, templateName: string): string {
  const target = rule.kind === 'deny' ? 'deny_rules' : 'ask_rules'
  const body = rule.body
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .map((line) => `  ${line}`)
    .join('\n')
  return `${target} contains {"rule_id": "${templateName}/${rule.id}", "reason": ${JSON.stringify(rule.reason)}} if {
${body}
}`
}

/**
 * Render one template into a Rego module.
 *
 * The module is self-contained: it declares its rules and any helpers they
 * reference, and nothing else. It deliberately defines no `decision` rule, so
 * two templates can never disagree about the verdict — the entrypoint owns that.
 * @param template - the template to render.
 * @returns the module source.
 */
export function renderTemplateModule(template: PolicyTemplate): string {
  const sections = [
    `# Generated by dsh-plugin-agentjail from template "${template.name}".`,
    '# Edit the template in the plugin source, or replace this file with your own rules.',
    `package ${TEMPLATE_PACKAGE_PREFIX}.${templatePackage(template.name)}`,
    '',
    `# ${template.description}`,
    '',
    ...template.rules.map((rule) => renderRule(rule, template.name)),
  ]
  if (template.helpers !== undefined && template.helpers.trim().length > 0) {
    sections.push('', '# Helpers referenced by the rules above.', '', template.helpers.trim())
  }
  return `${sections.join('\n')}\n`
}

/**
 * Render the entrypoint that merges every template into one decision.
 *
 * Deny wins over ask, and both win over the default allow. When several rules of
 * the same kind match, the lexicographically smallest rule id is reported, so
 * the verdict is deterministic rather than dependent on set iteration order.
 * @param templates - the templates to merge.
 * @returns the entrypoint module source.
 */
export function renderEntrypoint(templates: readonly PolicyTemplate[]): string {
  const imports = templates
    .map((template) => `import data.${TEMPLATE_PACKAGE_PREFIX}.${templatePackage(template.name)}`)
    .join('\n')

  const mergeDeny = templates
    .map(
      (template) =>
        `deny_rules contains rule if {\n  rule := ${templatePackage(template.name)}.deny_rules[_]\n}`,
    )
    .join('\n\n')

  const mergeAsk = templates
    .map(
      (template) =>
        `ask_rules contains rule if {\n  rule := ${templatePackage(template.name)}.ask_rules[_]\n}`,
    )
    .join('\n\n')

  return `# Generated by dsh-plugin-agentjail. Do not edit.
#
# This module is the daemon-facing entrypoint. It merges the rule sets of every
# installed template and resolves them into one verdict, in a fixed order:
# a matching deny wins over a matching ask, and both win over the default allow.

package ${POLICY_PACKAGE}

${imports}

# Every rule contributed by every template, flattened into two sets.
${mergeDeny}

${mergeAsk}

deny_ids contains rule_id if {
  some rule in deny_rules
  rule_id := rule.rule_id
}

ask_ids contains rule_id if {
  some rule in ask_rules
  rule_id := rule.rule_id
}

# The reported rule is the smallest matching id, so the outcome does not depend
# on set iteration order.
first_deny_id := id if {
  ids := sort([rule_id | rule_id := deny_ids[_]])
  count(ids) > 0
  id := ids[0]
}

first_ask_id := id if {
  not first_deny_id
  ids := sort([rule_id | rule_id := ask_ids[_]])
  count(ids) > 0
  id := ids[0]
}

decision := {"action": "deny", "rule_id": id, "reason": reason} if {
  id := first_deny_id
  some rule in deny_rules
  rule.rule_id == id
  reason := rule.reason
}

decision := {"action": "ask", "rule_id": id, "reason": reason} if {
  id := first_ask_id
  some rule in ask_rules
  rule.rule_id == id
  reason := rule.reason
}

# The flat action field is what the daemon reports when it only needs the verb.
default action := "allow"

action := "deny" if {
  first_deny_id
}

action := "ask" if {
  first_ask_id
}
`
}

