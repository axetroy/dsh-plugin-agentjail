/**
 * Look up a template by name.
 * @param name - the template name.
 * @returns the template, or `undefined` when unknown.
 */
export function findTemplate(name: string): PolicyTemplate | undefined {
  return POLICY_TEMPLATES.find((template) => template.name === name)
}

/**
 * Resolve a list of template names into templates.
 * @param names - template names to resolve.
 * @returns the resolved templates.
 * @throws Error when a name is unknown, so a typo cannot silently weaken policy.
 */
export function resolveTemplates(names: readonly string[]): PolicyTemplate[] {
  return names.map((name) => {
    const template = findTemplate(name)
    if (template === undefined) {
      const known = POLICY_TEMPLATES.map((candidate) => candidate.name).join(', ')
      throw new Error(`unknown policy template "${name}"; known templates: ${known}`)
    }
    return template
  })
}

/**
 * Render templates into a loadable policy bundle.
 *
 * Each template becomes one `.rego` file, and the returned map always ends with
 * the generated entrypoint. A `baseline` template is written as
 * `00-<name>.rego` so it sorts before additive templates, which keeps a reader's
 * first impression the posture rather than the exceptions.
 * @param templates - templates to render.
 * @returns the rendered files, keyed by file name.
 */
export function renderTemplateBundle(templates: readonly PolicyTemplate[]): Record<string, string> {
  const files: Record<string, string> = {}
  let baselineIndex = 0
  let additiveIndex = 0
  for (const template of templates) {
    const prefix =
      template.kind === 'baseline'
        ? `00-${String(baselineIndex++).padStart(2, '0')}`
        : `10-${String(additiveIndex++).padStart(2, '0')}`
    files[`${prefix}-${template.name}.rego`] = renderTemplateModule(template)
  }
  files[ENTRYPOINT_FILE] = renderEntrypoint(templates)
  return files
}

/**
 * Write a rendered bundle to a directory on disk.
 * @param directory - the target directory, created when absent.
 * @param templates - templates to render and write.
 * @returns the absolute paths written, in sorted order.
 */
export async function writeTemplateBundle(
  directory: string,
  templates: readonly PolicyTemplate[],
): Promise<string[]> {
  const files = renderTemplateBundle(templates)
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const written: string[] = []
  for (const [name, content] of Object.entries(files)) {
    const path = join(directory, name)
    await writeFile(path, content, { mode: 0o600 })
    written.push(path)
  }
  return written.sort()
}
